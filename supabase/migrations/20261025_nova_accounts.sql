create extension if not exists pgcrypto;

create table if not exists public.profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  display_name text check (display_name is null or char_length(display_name) <= 80),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.user_preferences (
  user_id uuid primary key references auth.users(id) on delete cascade,
  topics text[] not null default '{}',
  updated_at timestamptz not null default now()
);

create table if not exists public.saved_items (
  user_id uuid not null references auth.users(id) on delete cascade,
  item_id text not null,
  item jsonb not null,
  created_at timestamptz not null default now(),
  primary key (user_id, item_id)
);

create table if not exists public.user_activity (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  item_id text not null,
  action text not null check (action in ('open', 'save', 'unsave', 'explain', 'ask')),
  topic text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.ai_usage (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  item_id text not null,
  mode text not null check (mode in ('explain', 'ask')),
  model text,
  input_tokens integer,
  output_tokens integer,
  total_tokens integer,
  cached boolean not null default false,
  created_at timestamptz not null default now()
);

create index if not exists saved_items_user_id_idx on public.saved_items(user_id);
create index if not exists user_activity_user_id_created_at_idx on public.user_activity(user_id, created_at desc);
create index if not exists user_activity_topic_idx on public.user_activity(user_id, topic);
create index if not exists ai_usage_user_id_created_at_idx on public.ai_usage(user_id, created_at desc);

alter table public.profiles enable row level security;
alter table public.user_preferences enable row level security;
alter table public.saved_items enable row level security;
alter table public.user_activity enable row level security;
alter table public.ai_usage enable row level security;

drop policy if exists "profiles_select_own" on public.profiles;
create policy "profiles_select_own" on public.profiles for select to authenticated
using ((select auth.uid()) = user_id);

drop policy if exists "profiles_insert_own" on public.profiles;
